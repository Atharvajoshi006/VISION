# backend/apps/analytics/models.py
"""
Analytics – low‑level learning‑event tracking.

Each `LearningEvent` records a tiny interaction (view, play, hint request,
quiz attempt, …) together with a timestamp, optional foreign keys to the
related lesson/skill and a free‑form JSON payload.
"""
from __future__ import annotations

from django.db import models
from django.conf import settings


class LearningEvent(models.Model):
    """
    A single event generated by the front‑end (or a background task).

    The `timestamp` field is **mandatory** – it records when the event
    happened and is used by the OpenAPI generator and by any time‑series
    analytics you may build later.
    """

    class EventType(models.TextChoices):
        VIEW = "view", "View content"
        PLAY = "play", "Play video"
        ATTEMPT = "attempt", "Attempt exercise"
        SUBMIT = "submit", "Submit answer"
        HINT = "hint", "Request hint"
        FEEDBACK = "feedback", "Give feedback"

    # ------------------------------------------------------------------
    # Core relations
    # ------------------------------------------------------------------
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="learning_events",
    )
    lesson = models.ForeignKey(
        "courses.Lesson",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="events",
    )
    skill = models.ForeignKey(
        "courses.Skill",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="events",
    )

    # ------------------------------------------------------------------
    # Event data
    # ------------------------------------------------------------------
    event_type = models.CharField(max_length=20, choices=EventType.choices)

    # ---- NEW: timestamp field (auto‑filled on creation) -----------------
    occurred_at = models.DateTimeField(
        auto_now_add=True,
        help_text="When the event occurred (UTC).",
    )

    # Optional free‑form JSON that callers can use for any extra context.
    payload = models.JSONField(default=dict, blank=True)

    # ------------------------------------------------------------------
    # Indexes / ordering – useful for queries & the Swagger generator
    # ------------------------------------------------------------------
    class Meta:
        ordering = ["-occurred_at"]
        indexes = [
            models.Index(fields=["user", "event_type", "occurred_at"]),
        ]

    # ------------------------------------------------------------------
    # Human readable representation (useful in admin / debugging)
    # ------------------------------------------------------------------
    def __str__(self) -> str:
        return (
            f"{self.user.email} – {self.get_event_type_display()} "
            f"@ {self.timestamp.isoformat()}"
        )
