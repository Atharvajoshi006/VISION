"""
Vision AI — Assessments App Models
Quiz, question bank, and student attempt tracking.
"""

from django.db import models

from core.models import BaseModel


class QuestionType(models.TextChoices):
    MULTIPLE_CHOICE = "mcq", "Multiple Choice"
    TRUE_FALSE = "true_false", "True/False"
    SHORT_ANSWER = "short_answer", "Short Answer"


class Assessment(BaseModel):
    """
    A quiz linked to a lesson.
    Questions are generated by the AI pipeline (OpenAI) from the video transcript.
    """
    lesson = models.OneToOneField(
        "courses.Lesson",
        on_delete=models.CASCADE,
        related_name="assessment",
    )
    title = models.CharField(max_length=300)
    passing_score_percent = models.PositiveSmallIntegerField(default=70)
    time_limit_minutes = models.PositiveSmallIntegerField(null=True, blank=True)
    max_attempts = models.PositiveSmallIntegerField(default=3)
    is_ai_generated = models.BooleanField(default=True)

    class Meta:
        db_table = "assessments_assessment"


class Question(BaseModel):
    """
    Individual question within an assessment.
    options is stored as a JSONB list of {"text": str, "is_correct": bool}.
    """
    assessment = models.ForeignKey(
        Assessment,
        on_delete=models.CASCADE,
        related_name="questions",
    )
    question_text = models.TextField()
    question_type = models.CharField(
        max_length=20,
        choices=QuestionType.choices,
        default=QuestionType.MULTIPLE_CHOICE,
    )
    options = models.JSONField(
        default=list,
        help_text='[{"text": "...", "is_correct": true/false}]',
    )
    explanation = models.TextField(
        blank=True,
        help_text="Explanation shown to student after answering.",
    )
    difficulty_score = models.FloatField(default=0.5)
    topic_tag = models.CharField(max_length=100, blank=True)
    order_index = models.PositiveSmallIntegerField(default=0)

    class Meta:
        db_table = "assessments_question"
        ordering = ["order_index"]


class QuizAttempt(BaseModel):
    """
    Records a student's attempt at an assessment.
    answers_json: {"question_id": "selected_option_index"} for MCQ,
                  {"question_id": "text"} for short answer.
    """
    student = models.ForeignKey(
        "students.StudentProfile",
        on_delete=models.CASCADE,
        related_name="quiz_attempts",
    )
    assessment = models.ForeignKey(
        Assessment,
        on_delete=models.CASCADE,
        related_name="attempts",
    )
    attempt_number = models.PositiveSmallIntegerField(default=1)
    score_percent = models.FloatField(default=0.0)
    is_passed = models.BooleanField(default=False)
    answers_json = models.JSONField(default=dict)
    time_taken_seconds = models.PositiveIntegerField(default=0)
    started_at = models.DateTimeField()
    completed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        db_table = "assessments_quizattempt"
        indexes = [
            models.Index(fields=["student", "assessment"], name="idx_attempt_student_assessment"),
            models.Index(fields=["completed_at"], name="idx_attempt_completed"),
        ]

    def save(self, *args, **kwargs):
        """Auto-emit analytics event on quiz completion."""
        super().save(*args, **kwargs)
        if self.completed_at and self.pk:
            self._emit_analytics_event()

    def _emit_analytics_event(self):
        """Fire quiz result analytics event asynchronously."""
        from tasks.analytics_processing import emit_quiz_result_event
        emit_quiz_result_event.delay(str(self.id))
